# ── 文本知识库（用于向量检索） ──
KNOWLEDGE_TEXTS = []
for spot in SCENIC_SPOTS:
    text = f"{spot['name']}，{spot['desc']}"
    if spot.get("detail"):
        text = f"{spot['name']}：{spot['detail']}"
    else:
        if spot.get("highlights"):
            text += f" 主要看点：{spot['highlights']}。"
        if spot.get("duration"):
            text += f" 建议游览时间：{spot['duration']}。"
        if spot.get("level"):
            text += f" 景区等级：{spot['level']}。"
    KNOWLEDGE_TEXTS.append(text)

